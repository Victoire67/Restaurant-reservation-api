"""Measure the analytical queries with EXPLAIN ANALYZE, before and after sql/indexes.sql.

Usage (from the project root, containers running):
    python -m scripts.benchmark              # load bulk data, benchmark, restore seed
    python -m scripts.benchmark --skip-load  # bulk data is already loaded

Writes the plans and timings to docs/benchmark_results.md.
"""
import argparse
import re
import statistics
from datetime import datetime, timezone
from pathlib import Path

from app.analytics import NEARBY_QUERY, RANK_BY_CITY_QUERY
from app.availability import AVAILABLE_TABLES_QUERY
from app.db import close_pool, get_connection
from app.reviews import LATEST_REVIEWS_QUERY

ROOT = Path(__file__).resolve().parent.parent
BULK_SEED = ROOT / "sql" / "bulk_seed.sql"
DEV_SEED = ROOT / "sql" / "seed.sql"
INDEXES = ROOT / "sql" / "indexes.sql"
RESULTS = ROOT / "docs" / "benchmark_results.md"

RUNS_PER_QUERY = 7  # the median of several runs smooths out noise

PERFORMANCE_INDEXES = [
    "idx_reservations_table_time",
    "idx_tables_restaurant_capacity",
    "idx_restaurants_location",
    "idx_reviews_restaurant_latest",
]

# (title, SQL, parameters) - the exact queries the application runs
BENCHMARKS = [
    (
        "Availability CTE (restaurant 2500, 2 Nov 13:00-15:00 UTC, party of 4)",
        AVAILABLE_TABLES_QUERY,
        {
            "restaurant_id": 2500,
            "start_time": datetime(2026, 11, 2, 13, 0, tzinfo=timezone.utc),
            "end_time": datetime(2026, 11, 2, 15, 0, tzinfo=timezone.utc),
            "party_size": 4,
        },
    ),
    (
        "Location search (10 km around the centre of City 7)",
        NEARBY_QUERY,
        {"longitude": -170 + 7 * 37 % 340, "latitude": -50 + 7 * 17 % 100,
         "radius_m": 10_000, "limit": 20},
    ),
    (
        "Latest 20 reviews of restaurant 2500",
        LATEST_REVIEWS_QUERY,
        {"restaurant_id": 2500, "limit": 20},
    ),
    (
        "RANK() restaurants by average rating per city",
        RANK_BY_CITY_QUERY,
        {"min_reviews": 1},
    ),
]


def run_sql_file(path):
    with get_connection() as conn:
        conn.autocommit = True  # the files manage their own transactions / ANALYZE
        try:
            with conn.cursor() as cur:
                cur.execute(path.read_text(encoding="utf-8"))
        finally:
            conn.autocommit = False


def drop_performance_indexes():
    with get_connection() as conn:
        with conn.cursor() as cur:
            for name in PERFORMANCE_INDEXES:
                cur.execute(f"DROP INDEX IF EXISTS {name}")  # fixed names, not user input
    with get_connection() as conn:
        conn.autocommit = True
        try:
            with conn.cursor() as cur:
                cur.execute("ANALYZE")
        finally:
            conn.autocommit = False


def explain(sql, params):
    """Return (median execution time in ms, plan text of the last run)."""
    times = []
    plan = ""
    with get_connection() as conn:
        with conn.cursor() as cur:
            for _ in range(RUNS_PER_QUERY):
                cur.execute("EXPLAIN (ANALYZE, BUFFERS) " + sql, params)
                plan = "\n".join(row[0] for row in cur.fetchall())
                times.append(float(re.search(r"Execution Time: ([\d.]+) ms", plan).group(1)))
    return statistics.median(times), plan


def measure_all(label):
    results = {}
    for title, sql, params in BENCHMARKS:
        ms, plan = explain(sql, params)
        results[title] = (ms, plan)
        print(f"[{label}] {ms:9.3f} ms  {title}")
    return results


def write_report(before, after):
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python -m scripts.benchmark` on the bulk dataset "
        "(`sql/bulk_seed.sql`). Times are the median *Execution Time* of "
        f"{RUNS_PER_QUERY} `EXPLAIN (ANALYZE, BUFFERS)` runs.",
        "",
        "| Query | Without indexes | With `sql/indexes.sql` | Speed-up |",
        "|---|---:|---:|---:|",
    ]
    for title, _sql, _params in BENCHMARKS:
        b, a = before[title][0], after[title][0]
        lines.append(f"| {title} | {b:.3f} ms | {a:.3f} ms | {b / a:.1f}x |")

    for title, _sql, _params in BENCHMARKS:
        lines += [
            "",
            f"## {title}",
            "",
            "### Without indexes",
            "",
            "```text",
            before[title][1],
            "```",
            "",
            "### With indexes",
            "",
            "```text",
            after[title][1],
            "```",
        ]
    RESULTS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nReport written to {RESULTS.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--skip-load", action="store_true", help="bulk data is already loaded")
    args = parser.parse_args()

    try:
        if not args.skip_load:
            print("Loading bulk data (about a minute)...")
            run_sql_file(BULK_SEED)

        drop_performance_indexes()
        before = measure_all("before")

        run_sql_file(INDEXES)
        after = measure_all("after ")

        write_report(before, after)
    finally:
        if not args.skip_load:
            print("Restoring the development seed data...")
            run_sql_file(DEV_SEED)
        close_pool()


if __name__ == "__main__":
    main()
